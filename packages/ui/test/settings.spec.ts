import { expect, test } from '@playwright/test'

test('settings changes survive navigation, search changes the same value, and row reset restores its default', async ({ page }) => {
  await page.goto('/#settings')
  const settings = page.getByRole('region', { name: 'Settings', exact: true })
  const search = settings.getByRole('combobox', { name: 'Search settings' })
  await expect(search).toHaveAttribute('aria-expanded', 'false')
  await expect(search).not.toHaveAttribute('aria-controls')
  await expect(search).not.toHaveAttribute('aria-activedescendant')
  await expect(settings.getByRole('status')).toHaveText('')
  await search.press('ArrowDown')
  await search.press('Enter')
  await expect(search).toBeFocused()
  await expect(settings.getByRole('listbox')).toHaveCount(0)
  const smooth = settings.locator('[data-setting-id="canvas.smoothWheelZoom"]')
  await expect(smooth.getByRole('switch')).toHaveAttribute('aria-checked', 'false')
  await smooth.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(smooth.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
  await expect(smooth.getByRole('button', { name: 'Reset', exact: true })).toHaveCount(0)

  await settings.getByRole('link', { name: 'General', exact: true }).click()
  await expect(settings.getByRole('link', { name: 'General', exact: true })).toHaveAttribute('aria-current', 'page')
  await search.fill('canvas.grid.visible')
  await expect(search).toHaveAttribute('aria-expanded', 'true')
  await expect(settings.getByRole('option')).toHaveCount(1)
  await search.press('Enter')
  await expect(settings.getByRole('switch', { name: 'Show dot grid' })).toHaveAttribute('aria-checked', 'false')
  await search.press('Escape')
  await settings.getByRole('link', { name: 'Canvas', exact: true }).click()
  const grid = settings.locator('[data-setting-id="canvas.grid.visible"]')
  await expect(grid.getByRole('switch')).toHaveAttribute('aria-checked', 'false')
  const actions = grid.getByRole('button', { name: 'Actions for Show dot grid' })
  await actions.click()
  await page.getByRole('menuitem', { name: 'Reset to default', exact: true }).click()
  await expect(grid.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
  await expect(actions).toBeFocused()
  await search.fill('canvas.grid.visible')
  const resultSwitch = settings.getByRole('switch', { name: 'Show dot grid' })
  const resultActions = settings.getByRole('button', { name: 'Actions for Show dot grid' })
  await search.press('Enter')
  await expect(resultSwitch).toHaveAttribute('aria-checked', 'false')
  await resultActions.click()
  const reset = page.getByRole('menuitem', { name: 'Reset to default', exact: true })
  await expect(reset).toBeFocused()
  await expect(resultSwitch).toHaveAttribute('aria-checked', 'false')
  await reset.press('Enter')
  await expect(resultActions).toBeFocused()
  await expect(resultSwitch).toHaveAttribute('aria-checked', 'true')
  await expect(search).toHaveValue('canvas.grid.visible')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await resultActions.press('Enter')
  await page.getByRole('menuitem', { name: 'Copy setting ID', exact: true }).click()
  await expect(resultActions).toBeFocused()
  await expect(resultSwitch).toHaveAttribute('aria-checked', 'true')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('canvas.grid.visible')
  await resultActions.click()
  await page.getByRole('menuitem', { name: 'Copy setting ID', exact: true }).press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(resultActions).toBeFocused()
  await resultActions.click()
  await search.click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(search).toBeFocused()
  await expect(resultSwitch).toHaveAttribute('aria-checked', 'true')
  await search.fill('canvas.scrollBehavior')
  const scroll = settings.getByRole('combobox', { name: 'Canvas scroll behavior', exact: true })
  await scroll.selectOption('Pan')
  await expect(search).toHaveValue('canvas.scrollBehavior')
  await expect(scroll).toHaveValue('Pan')
  await settings.getByRole('button', { name: 'Actions for Canvas scroll behavior' }).click()
  await page.getByRole('menuitem', { name: 'Reset to default', exact: true }).click()
  await expect(scroll).toHaveValue('Zoom')
  await expect(settings.getByRole('button', { name: 'Actions for Canvas scroll behavior' })).toBeFocused()
  await search.fill('search.registryUrl')
  const address = settings.getByRole('textbox', { name: 'Node registry address' })
  await address.fill('https://example.org/nodes')
  await expect(address).toBeFocused()
  await address.press('End')
  await address.press('X')
  await expect(address).toHaveValue('https://example.org/nodesX')
  await search.fill('pack.example.prompt')
  await settings.getByRole('textbox', { name: 'Default prompt' }).fill('Updated in search')
  await search.fill('')
  await settings.getByRole('link', { name: 'Packs', exact: true }).click()
  await expect(settings.getByRole('textbox', { name: 'Default prompt' })).toHaveValue('Updated in search')
  await search.fill('glide')
  await expect(settings.locator('.dinkster-search-row-note mark')).toHaveText('Glide')
  await search.fill('no matching preference')
  await expect(settings.locator('.dinkster-search-empty-title')).toHaveText('No matching settings')
  await expect(settings.locator('.dinkster-search-empty-title')).toBeVisible()
  await search.press('Enter')
  await expect(search).toBeFocused()
  await search.fill('')
  await expect(search).toHaveAttribute('aria-expanded', 'false')
  await expect(search).not.toHaveAttribute('aria-controls')
  await expect(search).not.toHaveAttribute('aria-activedescendant')
  await expect(settings.getByRole('status')).toHaveText('')
  await search.press('ArrowUp')
  await search.press('Enter')
  await expect(search).toBeFocused()
  await expect(settings.getByRole('listbox')).toHaveCount(0)
  await expect(settings.getByRole('textbox', { name: 'Default prompt' })).toHaveValue('Updated in search')
})

test('shortcut recording cancels, stores the chosen keys, and resets only the changed shortcut', async ({ page }) => {
  await page.goto('/#settings')
  const settings = page.getByRole('region', { name: 'Settings', exact: true })
  await settings.getByRole('link', { name: 'Shortcuts' }).click()
  const save = settings.locator('[data-setting-id="workflow.save"]')
  const record = save.getByRole('button', { name: 'Record shortcut for Save workflow' })
  await expect(save.getByRole('button', { name: 'Reset', exact: true })).toHaveCount(0)
  await record.click()
  await expect(record).toContainText('Press the keys')
  await expect(record).toContainText('Esc cancels')
  await record.press('Escape')
  await expect(record).toHaveText('Ctrl+S')
  await record.click()
  await record.press('Control+Shift+P')
  await expect(record).toHaveText('Ctrl+Shift+P')
  await save.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(record).toHaveText('Ctrl+S')
  await expect(save.getByRole('button', { name: 'Reset', exact: true })).toHaveCount(0)
  await record.click()
  await record.press('Control+Enter')
  await expect(save.getByRole('status')).toHaveText('Also used by Run workflow.')
  await expect(settings.locator('[data-setting-id="workflow.queue"]').getByRole('status')).toHaveText('Also used by Save workflow.')
  await save.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(settings.locator('.dinkster-setting-warning')).toHaveCount(0)
  const search = settings.getByRole('combobox', { name: 'Search settings' })
  await search.fill('workflow.cancel')
  const unbound = settings.getByRole('button', { name: 'Record shortcut for Cancel current run' })
  await expect(unbound).toHaveText('None')
  await unbound.click()
  await unbound.press('Control+Shift+C')
  await expect(unbound).toHaveText('Ctrl+Shift+C')
  await expect(unbound).toBeFocused()
  await settings.getByRole('button', { name: 'Actions for Cancel current run' }).click()
  await expect(page.getByRole('menuitem', { name: 'Reset to default', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Remove shortcut', exact: true }).click()
  await expect(unbound).toHaveText('None')
  await settings.getByRole('button', { name: 'Actions for Cancel current run' }).click()
  await expect(page.getByRole('menuitem', { name: 'Remove shortcut', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Copy command ID', exact: true }).press('Escape')
  await search.fill('')
  await save.getByRole('button', { name: 'Actions for Save workflow' }).click()
  await page.getByRole('menuitem', { name: 'Remove shortcut', exact: true }).click()
  await expect(record).toHaveText('None')
  await save.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(record).toHaveText('Ctrl+S')
})
