/** Whether a name from outside the canvas, such as an extension badge's icon, is one the canvas paints. */
export const isCanvasIconName = (name: string): name is NonNullable<ToolboxButton['icon']> => Object.hasOwn(ICONS, name)

/**
 * Paint a Lucide icon with its 24-unit box drawn at exactly `size` px from
 * (x, y). A caller that sets an icon inside a larger box, such as a button,
 * works out the icon's size and place itself.
 */
export function paintToolboxIcon(
  ctx: CanvasRenderingContext2D,
  icon: NonNullable<ToolboxButton['icon']>,
  x: number,
  y: number,
  size: number,
  color: string,
): void {
  if (icon === 'circle') {
    const radius = size * canvasPaintTokens.icon.circleRadiusRatio
    ctx.save()
    ctx.beginPath()
    ctx.arc(x + size / 2, y + size / 2, radius, 0, Math.PI * 2)
    ctx.fillStyle = color
    ctx.fill()
    ctx.restore()
    return
  }
  paintIcon(ctx, ICONS[icon], x, y, size, color)
}

/** Paint the icon-only status for an after-generate controller chip. */
export function paintSeedControllerIcon(
  ctx: CanvasRenderingContext2D,
  mode: SeedControllerMode,
  x: number,
  y: number,
  size: number,
  color: string,
): void {
  paintIcon(ctx, CONTROLLER_ICONS[mode], x, y, size, color)
}

/** Paint a seed's after-run mode as drawn before the value of an in-row number. */
export function paintSeedModeIcon(
  ctx: CanvasRenderingContext2D,
  mode: SeedControllerMode,
  x: number,
  y: number,
  size: number,
  color: string,
): void {
  paintIcon(ctx, SEED_MODE_ICONS[mode], x, y, size, color)
}

function paintIcon(ctx: CanvasRenderingContext2D, nodes: IconNode, x: number, y: number, size: number, color: string): void {
  const scale = size / canvasPaintTokens.icon.viewBoxSize
  ctx.save()
  ctx.translate(x, y)
  ctx.scale(scale, scale)
  ctx.strokeStyle = color
  ctx.lineWidth = canvasPaintTokens.icon.stroke
  ctx.lineCap = 'round'
  ctx.lineJoin = 'round'
  for (const [tag, attrs] of nodes) {
    ctx.beginPath()
    if (tag === 'path') {
      ctx.stroke(new Path2D(attrs.d))
    } else if (tag === 'circle') {
      ctx.arc(Number(attrs.cx), Number(attrs.cy), Number(attrs.r), 0, Math.PI * 2)
      ctx.stroke()
    } else if (tag === 'line') {
      ctx.moveTo(Number(attrs.x1), Number(attrs.y1))
      ctx.lineTo(Number(attrs.x2), Number(attrs.y2))
      ctx.stroke()
    } else if (tag === 'rect') {
      const rx = Number(attrs.rx ?? 0)
      const ry = Number(attrs.ry ?? attrs.rx ?? 0)
      if (rx > 0 || ry > 0) {
        ctx.roundRect(
          Number(attrs.x ?? 0), Number(attrs.y ?? 0), Number(attrs.width), Number(attrs.height),
          { x: rx, y: ry },
        )
      } else {
        ctx.rect(Number(attrs.x ?? 0), Number(attrs.y ?? 0), Number(attrs.width), Number(attrs.height))
      }
      ctx.stroke()
    } else if (tag === 'ellipse') {
      ctx.ellipse(Number(attrs.cx), Number(attrs.cy), Number(attrs.rx), Number(attrs.ry), 0, 0, Math.PI * 2)
      ctx.stroke()
    } else if (tag === 'polyline' || tag === 'polygon') {
      const points = attrs.points!.trim().split(/\s+/).map((point) => point.split(',').map(Number))
      const first = points[0]
      if (!first) continue
      ctx.moveTo(first[0]!, first[1]!)
      for (const point of points.slice(1)) ctx.lineTo(point[0]!, point[1]!)
      if (tag === 'polygon') ctx.closePath()
      ctx.stroke()
    }
  }
  ctx.restore()
}
